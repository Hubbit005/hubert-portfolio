const { chromium } = require('playwright');
(async () => {
  const out = process.argv[2] || require('path').join(__dirname, 'out'); require('fs').mkdirSync(out, { recursive: true });
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
  const errs=[]; p.on('pageerror', e=>errs.push(e.message)); p.on('console', m=>{ if(m.type()==='error'||m.type()==='warning') errs.push(m.text())});
  await p.goto((process.env.BASE || 'http://localhost:8000') + '/#livingroom-booking', { waitUntil: 'load' });
  await p.waitForTimeout(2500);
  const root = p.locator('#proto-living');
  await root.scrollIntoViewIfNeeded(); await p.waitForTimeout(800);
  const shot = async (n) => { await p.waitForTimeout(500); await root.screenshot({ path: `${out}/lv-${n}.png` }); };
  await shot('01-date');
  await root.locator('.pk-day:not([disabled])').nth(1).click();
  await root.locator('[data-next="party"]').click();
  await root.locator('[data-party="4"]').click(); await shot('02-party');
  await root.locator('[data-next="time"]').click();
  await p.waitForTimeout(300); await shot('03-loading');
  await p.waitForTimeout(1000); await shot('04-times');
  await root.locator('.pk-time:not([disabled])').nth(3).click();
  await root.locator('[data-next="details"]').click();
  await root.locator('button[type=submit]').click(); await shot('05-errors');
  await root.locator('#name').fill('Anna Nowak'); await root.locator('#phone').fill('600 100 200'); await root.locator('#email').fill('anna@example.com');
  await root.locator('button[type=submit]').click(); await shot('06-review');
  await root.locator('[data-confirm]').click(); await p.waitForTimeout(200); await shot('07-sending');
  await p.waitForTimeout(1400); await shot('08-success');
  await p.locator('#proto-living .pk-switch').click(); await p.waitForTimeout(600); await shot('09-gallery');
  console.log(errs);
  await b.close();
})();
