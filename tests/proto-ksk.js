const { chromium } = require('playwright');
(async () => {
  const out = process.argv[2] || require('path').join(__dirname, 'out'); require('fs').mkdirSync(out, { recursive: true }); const W = +(process.argv[3]||1440);
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: W, height: 1000 }, isMobile: W<500, hasTouch: W<500 });
  const errs=[]; p.on('pageerror', e=>errs.push(e.message)); p.on('console', m=>{ if(m.type()==='error'||m.type()==='warning') errs.push(m.text())});
  await p.goto((process.env.BASE || 'http://localhost:8000') + '/#ksk-booking', { waitUntil: 'load' });
  await p.waitForTimeout(2500);
  const root = p.locator('#proto-ksk');
  const shot = async (n) => { await p.waitForTimeout(500); await root.screenshot({ path: `${out}/ksk-${W}-${n}.png` }); };
  await shot('01');
  await root.locator('input[value="premium"]').check({ force: true });
  await root.locator('[data-to="gruppe"]').click();
  console.log('weiter disabled without date:', await root.locator('[data-to="kontakt"]').isDisabled()); await shot('02-no-date');
  await root.locator('#ksk-size').fill('8'); await root.locator('#ksk-size').press('Tab'); await shot('03-small');
  await root.locator('#ksk-size').fill('20'); await root.locator('#ksk-size').press('Tab');
  await root.locator('.pk-day').nth(3).click(); await root.locator('.pk-time:not([disabled])').first().click(); await shot('04-ok');
  await root.locator('[data-to="kontakt"]').click();
  await root.locator('button[type=submit]').click(); await shot('05-errors');
  await root.locator('#name').fill('Julia Becker'); await root.locator('#email').fill('julia@firma.de'); await root.locator('#tel').fill('+49 30 1234567');
  await root.locator('#quelle').selectOption('Sonstiges'); await p.waitForTimeout(200); await root.locator('#quelleText').fill('Messe');
  await root.locator('button[type=submit]').click(); await shot('06-pruefen');
  await root.locator('[data-send]').click(); await p.waitForTimeout(1500); await shot('07-sent');
  await root.locator('.pk-switch').click(); await p.waitForTimeout(500); await shot('08-gallery');
  console.log(errs); await b.close();
})();
